def _dewpoint(ds, temperature, dewpoint, relative_humidity):
    if dewpoint in ds:
        return ds[dewpoint]
    if relative_humidity in ds:
        from ..io.sounding import (
            dewpoint_from_vapor_pressure,
            saturation_vapor_pressure,
        )

        rh = ds[relative_humidity]
        if rh.attrs.get("units") == "%" or float(rh.max(skipna=True).fillna(0)) > 2:
            raise ValueError("relative_humidity must be a fraction (units '1')")
        return dewpoint_from_vapor_pressure(
            rh * saturation_vapor_pressure(ds[temperature])
        )
    return xr.full_like(ds[temperature], np.nan)


def _check_si(t, p):
    tmax = float(np.nanmax(t)) if np.isfinite(t).any() else np.nan
    pmax = float(np.nanmax(p)) if np.isfinite(p).any() else np.nan
    if np.isfinite(tmax) and tmax < 150:
        raise ValueError("temperature must be in K")
    if np.isfinite(pmax) and pmax < 2000:
        raise ValueError("pressure must be in Pa")


def potential_temperatures(
    ds,
    *,
    temperature="temperature",
    pressure="pressure",
    dewpoint="dewpoint",
    relative_humidity="relative_humidity",
    engine="auto",
    n_threads=None,
):
    """
    Mixing ratio and potential, virtual potential and equivalent potential
    temperature.

    Parameters
    ----------
    ds : xarray.Dataset
        Temperature (K) and pressure (Pa), with the dew point (K) or, failing
        that, the relative humidity (fraction), e.g. a station network from
        :func:`radarx.io.read_sticknet`, a sounding from
        :mod:`radarx.io.sounding` or gridded fields. Without humidity only the
        potential temperature is finite.
    temperature, pressure, dewpoint, relative_humidity : str, optional
        Variable names.
    engine : {"auto", "compiled", "numpy"}, optional
        Kernel implementation.
    n_threads : int, optional
        Threads for the compiled kernel. Default: all cores.

    Returns
    -------
    xarray.Dataset
        ``mixing_ratio``, ``potential_temperature``,
        ``virtual_potential_temperature`` and
        ``equivalent_potential_temperature`` on the coordinates of ``ds``.

    References
    ----------
    Bolton, D., 1980: The computation of equivalent potential temperature.
    *Mon. Wea. Rev.*, **108** (7), 1046-1053,
    https://doi.org/10.1175/1520-0493(1980)108<1046:TCOEPT>2.0.CO;2
    """
    t, p = xr.broadcast(ds[temperature], ds[pressure])
    td = _dewpoint(ds, temperature, dewpoint, relative_humidity)
    t, p, td = xr.broadcast(t, p, td)
    _check_si(t.values, p.values)
    k = _kernel(engine)
    res = np.asarray(
        k.thermo(
            _f64(t.values.reshape(-1)),
            _f64(p.values.reshape(-1)),
            _f64(td.values.reshape(-1)),
            n_threads=_threads(n_threads),
        )
    )
    names = (
        "mixing_ratio",
        "potential_temperature",
        "virtual_potential_temperature",
        "equivalent_potential_temperature",
    )
    out = xr.Dataset(
        {
            n: t.copy(data=res[i].reshape(t.shape)).rename(n).assign_attrs(_ATTRS[n])
            for i, n in enumerate(names)
        }
    )
    for n in names:
        out[n].attrs = dict(_ATTRS[n])
    return out


def buoyancy(theta_v, reference, *, condensate=None):
    """
    Buoyancy from the virtual potential temperature.

    :math:`B = g (\\theta_v - \\overline{\\theta_v}) / \\overline{\\theta_v}
    - g r_c`.

    Parameters
    ----------
    theta_v : xarray.DataArray
        Virtual potential temperature (K).
    reference : xarray.DataArray or float
        Reference (environmental) virtual potential temperature, broadcast
        against ``theta_v``.
    condensate : xarray.DataArray or float, optional
        Condensate mixing ratio (kg kg-1) for the hydrometeor loading. Without
        it the buoyancy of precipitating air is overestimated (the cold-pool
        intensity underestimated).

    Returns
    -------
    xarray.DataArray
        ``buoyancy`` (m s-2) on the coordinates of ``theta_v``.

    References
    ----------
    Markowski, P., and Y. Richardson, 2010: *Mesoscale Meteorology in
    Midlatitudes*. Wiley-Blackwell, 407 pp.,
    https://doi.org/10.1002/9780470682104
    """
    b = G * (theta_v - reference) / reference
    if condensate is not None:
        b = b - G * condensate
    b = b.rename("buoyancy")
    b.attrs = dict(_ATTRS["buoyancy"])
    return b


def cold_pool_perturbation(
    ds,
    reference,
    *,
    dim="time",
    variables=None,
    engine="auto",
    n_threads=None,
):
    """
    Perturbations from a reference state and the buoyancy.

    Parameters
    ----------
    ds : xarray.Dataset
        Observations with ``temperature`` and ``pressure`` (and humidity),
        e.g. stations on ``(station, time)`` or a post-storm sounding on
        ``height``. Missing potential temperatures are computed with
        :func:`potential_temperatures`.
    reference : slice, xarray.Dataset
        The reference state: a ``slice`` of ``dim`` (e.g. a pre-storm time
        window) averaged over that window for every other coordinate (every
        station), or a Dataset (e.g. a pre-storm sounding) with the same
        variables. A reference sounding on other heights is interpolated to
        the heights of ``ds`` (:func:`radarx.io.sounding.interpolate_profile`).
    dim : str, optional
        Dimension that ``reference`` slices. Default ``"time"``.
    variables : list of str, optional
        Variables to perturb. Default: the potential temperatures,
        ``temperature``, ``pressure``, ``dewpoint`` and ``mixing_ratio``
        where present.
    engine, n_threads : optional
        For :func:`potential_temperatures`.

    Returns
    -------
    xarray.Dataset
        ``<name>_perturbation`` for every variable (the observation minus the
        reference), the reference ``virtual_potential_temperature_reference``
        and ``buoyancy`` from the virtual potential temperature.
    """
    ds = _with_thermo(ds, engine, n_threads)
    if isinstance(reference, slice):
        ref = ds.sel({dim: reference}).mean(dim, keep_attrs=True)
    elif isinstance(reference, xr.Dataset):
        ref = _with_thermo(reference, engine, n_threads)
        if "height" in ds.dims and "height" in ref.dims:
            if ref.sizes["height"] != ds.sizes["height"] or not np.allclose(
                ref["height"].values, ds["height"].values
            ):
                from ..io.sounding import interpolate_profile

                ref = interpolate_profile(
                    ref,
                    ds["height"],
                    [v for v in ref.data_vars if "height" in ref[v].dims],
                )
    else:
        raise TypeError("reference must be a slice or an xarray.Dataset")
    if variables is None:
        variables = [
            v
            for v in (
                "potential_temperature",
                "virtual_potential_temperature",
                "equivalent_potential_temperature",
                "temperature",
                "dewpoint",
                "mixing_ratio",
                "pressure",
            )
            if v in ds and v in ref
        ]
    out = xr.Dataset()
    for v in variables:
        d = (ds[v] - ref[v]).rename(f"{v}_perturbation")
        d.attrs = {
            "long_name": f"{ds[v].attrs.get('long_name', v)} minus reference",
            "units": ds[v].attrs.get("units", ""),
        }
        out[d.name] = d
    thv0 = ref["virtual_potential_temperature"]
    out["virtual_potential_temperature_reference"] = thv0.assign_attrs(
        long_name="Reference virtual potential temperature", units="K"
    )
    out["buoyancy"] = buoyancy(ds["virtual_potential_temperature"], thv0)
    return out


def _with_thermo(ds, engine, n_threads):
    if "virtual_potential_temperature" in ds:
        return ds
    pt = potential_temperatures(ds, engine=engine, n_threads=n_threads)
    return ds.assign({name: pt[name] for name in pt.data_vars})


