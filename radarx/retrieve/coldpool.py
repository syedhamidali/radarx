def _height_of(obj, dim, height):
    """Height of every element of ``obj`` (DataArray broadcast like ``obj``)."""
    if height is not None:
        z = height if isinstance(height, xr.DataArray) else obj[height]
    elif dim in obj.coords:
        z = obj[dim]
    else:
        raise ValueError(f"no coordinate {dim!r} to use as height; pass height=")
    return z


def _columns(arrays, dim, z):
    """Stack DataArrays into (ncol, nz) NumPy columns along ``dim``.

    Returns the columns (in the order of ``arrays``), the height columns,
    the dimensions and coordinates of the result without ``dim``, and the
    shape to restore.
    """
    arrays = xr.broadcast(*arrays, z)
    z = arrays[-1]
    arrays = arrays[:-1]
    if dim not in arrays[0].dims:
        raise ValueError(f"dimension {dim!r} not found in {arrays[0].dims}")
    other = [d for d in arrays[0].dims if d != dim]
    order = other + [dim]
    shape = tuple(arrays[0].sizes[d] for d in other)
    nz = arrays[0].sizes[dim]
    cols = [_f64(a.transpose(*order).values.reshape(-1, nz)) for a in arrays]
    zc = _f64(z.transpose(*order).values.reshape(-1, nz))
    # levels must increase along each column
    if nz > 1:
        first = np.nanmedian(np.diff(zc, axis=1))
        if np.isfinite(first) and first < 0:
            cols = [_f64(c[:, ::-1]) for c in cols]
            zc = _f64(zc[:, ::-1])
    coords = {
        k: v
        for k, v in arrays[0].coords.items()
        if dim not in v.dims and set(v.dims) <= set(other)
    }
    return cols, zc, other, coords, shape


def _per_column(value, template_dims, coords, shape):
    """Scalar or DataArray ``value`` as a flat array, one per column."""
    if value is None:
        return np.full(int(np.prod(shape, dtype=np.int64)), np.nan)
    if isinstance(value, xr.DataArray):
        tmpl = xr.DataArray(np.zeros(shape), dims=template_dims)
        value = value.broadcast_like(tmpl).transpose(*template_dims)
        return _f64(value.values.reshape(-1))
    return np.full(int(np.prod(shape, dtype=np.int64)), float(value))


