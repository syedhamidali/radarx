def baroclinic_generation(
    buoyancy,
    *,
    x="x",
    y="y",
    u=None,
    v=None,
    storm_motion=(0.0, 0.0),
    engine="auto",
    n_threads=None,
):
    """
    Baroclinic generation of horizontal vorticity, :math:`\\partial B /
    \\partial y` and :math:`-\\partial B / \\partial x`.

    Parameters
    ----------
    buoyancy : xarray.DataArray
        Buoyancy (m s-2) on a grid with horizontal dimensions ``y`` and ``x``
        (coordinates in m), and any others (height, time), e.g.
        ``buoyancy(theta_v, reference)`` of a radarx grid, or
        :math:`g\\,\\Delta T / T` of the accumulated evaporative cooling of
        :func:`radarx.retrieve.integrate_evaporation`. A vertical cross-section
        without ``y`` gives only :math:`-\\partial B / \\partial x`.
    x, y : str, optional
        Horizontal dimensions. Default ``"x"`` and ``"y"``.
    u, v : xarray.DataArray, optional
        Wind components along ``x`` and ``y`` (m s-1), e.g. multi-Doppler
        winds, broadcastable against ``buoyancy``. With them the generation is
        split into streamwise and crosswise parts relative to the
        storm-relative wind.
    storm_motion : tuple of float or xarray.Dataset, optional
        Storm motion ``(cx, cy)`` (m s-1) subtracted from ``u`` and ``v``, or
        a Dataset with ``u`` and ``v`` (e.g.
        :func:`radarx.retrieve.bunkers_storm_motion`). Default (0, 0).
    engine : {"auto", "compiled", "numpy"}, optional
        Kernel implementation.
    n_threads : int, optional
        Threads for the compiled kernel. Default: all cores.

    Returns
    -------
    xarray.Dataset
        ``dB_dx`` and ``dB_dy`` (s-2), the generation rates
        ``vorticity_x_generation`` (:math:`\\partial B/\\partial y`),
        ``vorticity_y_generation`` (:math:`-\\partial B/\\partial x`) and
        ``horizontal_vorticity_generation`` (their magnitude), all in s-2,
        and, with winds, ``streamwise_vorticity_generation`` and
        ``crosswise_vorticity_generation`` (s-2).

    References
    ----------
    Rotunno, R., J. B. Klemp, and M. L. Weisman, 1988: A theory for strong,
    long-lived squall lines. *J. Atmos. Sci.*, **45** (3), 463-485,
    https://doi.org/10.1175/1520-0469(1988)045<0463:ATFSLL>2.0.CO;2

    Davies-Jones, R., 1984: Streamwise vorticity: The origin of updraft
    rotation in supercell storms. *J. Atmos. Sci.*, **41** (20), 2991-3006,
    https://doi.org/10.1175/1520-0469(1984)041<2991:SVTOOU>2.0.CO;2
    """
    if x not in buoyancy.dims:
        raise ValueError(f"dimension {x!r} not found in {buoyancy.dims}")
    has_y = y in buoyancy.dims
    b = buoyancy if has_y else buoyancy.expand_dims({y: [0.0]})
    other = [d for d in b.dims if d not in (y, x)]
    arr = b.transpose(*other, y, x)
    ny, nx = arr.sizes[y], arr.sizes[x]
    flat = _f64(arr.values.reshape(-1, ny, nx))
    xc = _f64(arr[x].values) if x in arr.coords else np.arange(nx, dtype=float)
    yc = _f64(arr[y].values) if y in arr.coords else np.arange(ny, dtype=float)
    k = _kernel(engine)
    res = np.asarray(k.gradient(flat, xc, yc, n_threads=_threads(n_threads)))
    dims = tuple(other) + (y, x)
    shape = arr.shape
    dbdx = arr.copy(data=res[0].reshape(shape))
    dbdy = arr.copy(data=res[1].reshape(shape))
    if not has_y:
        dbdx = dbdx.isel({y: 0}, drop=True)
        dbdy = None
        dims = tuple(d for d in dims if d != y)
    order = [d for d in buoyancy.dims]
    out = xr.Dataset(coords={k_: c for k_, c in buoyancy.coords.items()})
    out["dB_dx"] = dbdx.transpose(*order).assign_attrs(
        long_name="Buoyancy gradient along x", units="s-2"
    )
    gen_y = (-out["dB_dx"]).assign_attrs(
        long_name="Baroclinic generation of horizontal vorticity along y " "(-dB/dx)",
        units="s-2",
    )
    out["vorticity_y_generation"] = gen_y
    if dbdy is None:
        out.attrs["comment"] = "vertical cross-section: only -dB/dx"
        return out
    out["dB_dy"] = dbdy.transpose(*order).assign_attrs(
        long_name="Buoyancy gradient along y", units="s-2"
    )
    gen_x = (
        out["dB_dy"]
        .copy()
        .assign_attrs(
            long_name="Baroclinic generation of horizontal vorticity along x (dB/dy)",
            units="s-2",
        )
    )
    out["vorticity_x_generation"] = gen_x
    out["horizontal_vorticity_generation"] = np.hypot(gen_x, gen_y).assign_attrs(
        long_name="Magnitude of the baroclinic generation of horizontal vorticity",
        units="s-2",
    )
    if u is not None and v is not None:
        if isinstance(storm_motion, xr.Dataset):
            cx, cy = storm_motion["u"], storm_motion["v"]
        else:
            cx, cy = storm_motion
        ur, vr = u - cx, v - cy
        speed = np.hypot(ur, vr)
        sx, sy = ur / speed, vr / speed
        out["streamwise_vorticity_generation"] = (gen_x * sx + gen_y * sy).assign_attrs(
            long_name="Baroclinic generation of streamwise horizontal vorticity",
            units="s-2",
            comment="component along the storm-relative wind",
        )
        out["crosswise_vorticity_generation"] = (-gen_x * sy + gen_y * sx).assign_attrs(
            long_name="Baroclinic generation of crosswise horizontal vorticity",
            units="s-2",
            comment="component 90 degrees to the left of the storm-relative wind",
        )
    return out


